func runOneModelConcurrentReplay(seed int64, counters *modelCounters) error {
	root, err := os.MkdirTemp("", "hideout-lifecycle-model-concurrent-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(root)
	_ = os.Chmod(root, 0o700)
	clock := &modelClock{now: time.Date(2026, 7, 16, 11, 0, 0, 0, time.UTC)}
	coordinator, err := newModelCoordinator(root, fmt.Sprintf("daemon-model-concurrent-%d", seed), clock, false, nil)
	if err != nil {
		return err
	}
	if err := coordinator.Reconcile(context.Background(), ReconcileInput{
		EnvironmentID: "env-model", InstanceName: "hideout-model",
		Observation: modelObservation(clock, "01234567-89ab-cdef-0123-456789abcdef", backend.LifecycleRunning),
	}); err != nil {
		return err
	}
	start := make(chan struct{})
	var wg sync.WaitGroup
	for index := 0; index < 4; index++ {
		index := index
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			switch index {
			case 0, 1:
				registration, attachErr := modelAttach(coordinator, clock, fmt.Sprintf("ses-concurrent-%d", index), "01234567-89ab-cdef-0123-456789abcdef")
				if attachErr == nil {
					_ = registration.Finish(context.Background(), nil)
				}
			case 2:
				clock.advance(DefaultIdleGrace)
			case 3:
				_ = coordinator.Reconcile(context.Background(), ReconcileInput{
					EnvironmentID: "env-model", InstanceName: "hideout-model",
					Observation: modelObservation(clock, "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", backend.LifecycleRunning),
				})
			}
		}()
	}
	close(start)
	done := make(chan struct{})
	go func() { wg.Wait(); close(done) }()
	select {
	case <-done:
	case <-time.After(modelConcurrentWaitBound):
		return fmt.Errorf("concurrent lifecycle replay seed=%d exceeded %s", seed, modelConcurrentWaitBound)
	}
	if err := validateModelStore(JournalStore{Root: root}, counters); err != nil {
		return fmt.Errorf("concurrent replay seed=%d: %w", seed, err)
	}
	_ = coordinator.Close()
	counters.scenario()
	return nil
}

func validateModelStore(store JournalStore, counters *modelCounters) error {
	journal, err := store.Load("env-model")
	if err != nil {
		return err
	}
	return validateModelJournal(journal, counters)
}

func validateModelCoordinator(coordinator *Coordinator, counters *modelCounters) error {
	coordinator.mu.Lock()
	state := coordinator.environments["env-model"]
	if state == nil {
		coordinator.mu.Unlock()
		return nil
	}
	journal := state.journal
	observation := state.observation
	coordinator.mu.Unlock()
	if err := validateModelJournal(journal, counters); err != nil {
		return err
	}
	if journal.Incarnation != nil && observation.State == backend.LifecycleUnknown {
		evaluation, err := EvaluateAutoStop(EvaluationInput{
			Incarnation: *journal.Incarnation, Resources: journal.Resources, Observation: observation,
			GraceExpired: true, ReconciliationComplete: journal.Reconciliation.State == "complete",
			CurrentDaemonOwnsAttempt: true,
		})
		if err == nil && evaluation.Allowed {
			return errors.New("unknown backend observation allowed stop")
		}
		counters.passInvariant("unknownStateNeverStops")
	}
	return nil
}

func validateModelJournal(journal Journal, counters *modelCounters) error {
	if err := journal.Validate(); err != nil {
		return err
	}
	counters.passInvariant("journalValidAfterEachStep")
	if err := ValidateGraph(journal.Resources, true); err != nil {
		return err
	}
	counters.passInvariant("dependencyGraphAcyclic")
	byKey := map[string]Resource{}
	for _, resource := range journal.Resources {
		if resource.Ref.Generation != journal.StartGeneration || resource.Owner.Generation != journal.StartGeneration {
			return errors.New("resource from another generation remained authoritative")
		}
		byKey[resource.Ref.Key()] = resource
	}
	counters.passInvariant("generationIsolation")
	for _, resource := range journal.Resources {
		if !resource.IsPossiblyLive() {
			continue
		}
		for _, dependency := range resource.Dependencies {
			if byKey[dependency.Ref.Key()].State == StateReleased {
				return errors.New("live resource depends on released resource")
			}
		}
	}
	counters.passInvariant("liveResourceNeverDependsOnReleasedResource")
	for _, resource := range journal.Resources {
		if resource.Ref.Kind != KindWorkspaceGuestView {
			continue
		}
		dependencies := map[ResourceKind]bool{}
		for _, dependency := range resource.Dependencies {
			dependencies[dependency.Ref.Kind] = dependency.StopMode == StopModeDrain
			if _, ok := byKey[dependency.Ref.Key()]; !ok {
				return errors.New("workspace view dependency is absent")
			}
		}
		for _, kind := range []ResourceKind{KindBackendIncarnation, KindRunSession, KindWorkspaceHostProvider} {
			if !dependencies[kind] {
				return fmt.Errorf("workspace view lacks closed dependency %s", kind)
			}
		}
		counters.passInvariant("workspaceViewHasClosedDependencies")
	}
	return nil
}

func modelStatusHasResource(status Status, kind ResourceKind, state ResourceState) bool {
	for _, list := range [][]ResourceSummary{status.Pins, status.Drains, status.Orphans} {
		for _, resource := range list {
			if resource.Kind == kind && (state == "" || resource.State == state) {
				return true
			}
		}
	}
	return false
}

func verifyModelCoverage(counters *modelCounters) error {
	for _, event := range requiredModelEvents {
		if !counters.covered[event] {
			return fmt.Errorf("lifecycle model did not execute required event %q", event)
		}
	}
	for _, invariant := range requiredModelInvariants {
		if !counters.invariants[invariant] {
			return fmt.Errorf("lifecycle model invariant failed: %s", invariant)
		}
	}
	if counters.stopsWithLiveClient != 0 || counters.duplicateGenerationStops != 0 {
		return errors.New("lifecycle model observed an unsafe stop")
	}
	return nil
}

func (c *modelCounters) cover(events ...string) {
	c.mu.Lock()
	defer c.mu.Unlock()
	for _, event := range events {
		c.covered[event] = true
	}
}

func (c *modelCounters) step() {
	c.mu.Lock()
	c.transitions++
	c.mu.Unlock()
}

func (c *modelCounters) scenario() {
	c.mu.Lock()
	c.scenarios++
	c.mu.Unlock()
}

func (c *modelCounters) passInvariant(names ...string) {
	c.mu.Lock()
	for _, name := range names {
		c.invariants[name] = true
	}
	c.mu.Unlock()
}

func modelConstrainedPermutations(values []string, keep func([]string) bool) [][]string {
	var out [][]string
	working := append([]string(nil), values...)
	var visit func(int)
	visit = func(index int) {
		if index == len(working) {
			candidate := append([]string(nil), working...)
			if keep(candidate) {
				out = append(out, candidate)
			}
			return
		}
		for next := index; next < len(working); next++ {
			working[index], working[next] = working[next], working[index]
			visit(index + 1)
			working[index], working[next] = working[next], working[index]
		}
	}
	visit(0)
	return out
}

func modelIndexOf(values []string, value string) int {
	for index, candidate := range values {
		if candidate == value {
			return index
		}
	}
	return len(values)
}
