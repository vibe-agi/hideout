func runModelPersistedReplays(counters *modelCounters) error {
	random := rand.New(rand.NewSource(36036017))
	for scenario := 0; scenario < modelPersistedReplaySeeds; scenario++ {
		seed := random.Int63()
		if err := runOneModelPersistedReplay(seed, scenario == modelPersistedReplaySeeds-1, counters); err != nil {
			return err
		}
	}
	return nil
}

func runOneModelPersistedReplay(seed int64, corrupt bool, counters *modelCounters) error {
	random := rand.New(rand.NewSource(seed))
	root, err := os.MkdirTemp("", "hideout-lifecycle-model-replay-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(root)
	_ = os.Chmod(root, 0o700)
	clock := &modelClock{now: time.Date(2026, 7, 16, 10, 0, 0, 0, time.UTC)}
	store := JournalStore{Root: root}
	coordinator, err := newModelCoordinator(root, "daemon-model-replay-0", clock, false, nil)
	if err != nil {
		return err
	}
	bootID := "01234567-89ab-cdef-0123-456789abcdef"
	if err := coordinator.Reconcile(context.Background(), ReconcileInput{
		EnvironmentID: "env-model", InstanceName: "hideout-model", Observation: modelObservation(clock, bootID, backend.LifecycleRunning),
	}); err != nil {
		return err
	}
	registrations := map[string]Registration{}
	for step := 0; step < modelReplaySteps; step++ {
		client := fmt.Sprintf("ses-%d", random.Intn(2))
		switch random.Intn(6) {
		case 0:
			if registrations[client] == nil {
				if registration, attachErr := modelAttach(coordinator, clock, client, bootID); attachErr == nil {
					registrations[client] = registration
				}
			}
		case 1:
			if registration := registrations[client]; registration != nil {
				_ = registration.Finish(context.Background(), nil)
				delete(registrations, client)
			}
		case 2:
			clock.advance(time.Duration(random.Intn(int(DefaultIdleGrace/time.Millisecond)+1)) * time.Millisecond)
		case 3:
			_ = coordinator.Close()
			registrations = map[string]Registration{}
			coordinator, err = newModelCoordinator(root, fmt.Sprintf("daemon-model-replay-%d", step+1), clock, false, nil)
			if err != nil {
				return err
			}
			_ = coordinator.Reconcile(context.Background(), ReconcileInput{
				EnvironmentID: "env-model", InstanceName: "hideout-model", Observation: modelObservation(clock, bootID, backend.LifecycleRunning),
			})
		case 4:
			_ = coordinator.Reconcile(context.Background(), ReconcileInput{
				EnvironmentID: "env-model", InstanceName: "hideout-model", Observation: modelObservation(clock, "", backend.LifecycleUnknown),
			})
		case 5:
			_ = coordinator.Reconcile(context.Background(), ReconcileInput{
				EnvironmentID: "env-model", InstanceName: "hideout-model", Observation: modelObservation(clock, bootID, backend.LifecycleRunning),
			})
		}
		counters.step()
		if loadErr := validateModelStore(store, counters); loadErr != nil {
			return fmt.Errorf("persisted replay seed=%d step=%d: %w", seed, step, loadErr)
		}
	}
	_ = coordinator.Close()
	counters.scenario()
	if !corrupt {
		return nil
	}
	dir, err := store.environmentDir("env-model", false)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, journalFileName), []byte("{\"schema\":"), 0o600); err != nil {
		return err
	}
	if _, err := store.Load("env-model"); err == nil {
		return errors.New("corrupt lifecycle journal was accepted")
	}
	return nil
}

