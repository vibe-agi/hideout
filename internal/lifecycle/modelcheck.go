func runModelCrashAndRecovery(counters *modelCounters) error {
	root, err := os.MkdirTemp("", "hideout-lifecycle-model-recovery-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(root)
	_ = os.Chmod(root, 0o700)
	clock := &modelClock{now: time.Date(2026, 7, 16, 8, 0, 0, 0, time.UTC)}
	first, err := newModelCoordinator(root, "daemon-model-before-crash", clock, false, nil)
	if err != nil {
		return err
	}
	_, err = modelAttach(first, clock, "ses-recovery", "01234567-89ab-cdef-0123-456789abcdef")
	if err != nil {
		return err
	}
	if err := first.Close(); err != nil {
		return err
	}
	counters.cover("daemon-crash")
	second, err := newModelCoordinator(root, "daemon-model-after-crash", clock, false, nil)
	if err != nil {
		return err
	}
	if err := second.Reconcile(context.Background(), ReconcileInput{
		EnvironmentID: "env-model", InstanceName: "hideout-model",
		Observation: modelObservation(clock, "", backend.LifecycleUnknown),
	}); err != nil {
		return err
	}
	statuses := second.Snapshot()
	if len(statuses) != 1 || statuses[0].Activity != ActivityBlocked || !modelStatusHasResource(statuses[0], KindWorkspaceGuestView, StateOrphaned) {
		return fmt.Errorf("workspace restart uncertainty did not remain orphaned: %+v", statuses)
	}
	counters.cover("backend-observation-unknown", "workspace-recovery-unproved")
	if err := second.Reconcile(context.Background(), ReconcileInput{
		EnvironmentID: "env-model", InstanceName: "hideout-model",
		Observation: modelObservation(clock, "01234567-89ab-cdef-0123-456789abcdef", backend.LifecycleRunning),
	}); err != nil {
		return err
	}
	statuses = second.Snapshot()
	if len(statuses) != 1 || modelStatusHasResource(statuses[0], KindWorkspaceHostProvider, "") || modelStatusHasResource(statuses[0], KindWorkspaceGuestView, "") {
		return fmt.Errorf("workspace restart re-adopted prior provider state: %+v", statuses)
	}
	if _, available := second.ActiveAttachObservation(context.Background(), "env-model", "hideout-model"); available {
		return errors.New("workspace restart produced attach authority without a new registration")
	}
	counters.cover("backend-observation-success", "recovery", "workspace-recovery-absence")
	counters.passInvariant("workspaceRestartDoesNotReadopt")
	if err := second.Reconcile(context.Background(), ReconcileInput{
		EnvironmentID: "env-model", InstanceName: "hideout-model",
		Observation: modelObservation(clock, "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee", backend.LifecycleRunning),
	}); err != nil {
		return err
	}
	counters.cover("external-boot-change")
	if err := validateModelCoordinator(second, counters); err != nil {
		return err
	}
	if err := second.Close(); err != nil {
		return err
	}
	counters.scenario()
	return nil
}

