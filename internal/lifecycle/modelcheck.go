// ModelCheckReport is generated by executing the production lifecycle
// coordinator and reducers. It contains no operator or target data.
type ModelCheckReport struct {
	Schema                    string          `json:"schema"`
	Status                    string          `json:"status"`
	ExhaustiveSequences       int             `json:"exhaustiveSequences"`
	ExploredTransitions       int             `json:"exploredTransitions"`
	ScenarioCount             int             `json:"scenarioCount"`
	PersistedReplaySeeds      int             `json:"persistedReplaySeeds"`
	ConcurrentReplaySeeds     int             `json:"concurrentReplaySeeds"`
	StepsPerPersistedReplay   int             `json:"stepsPerPersistedReplay"`
	ConcurrentWaitBoundMS     int             `json:"concurrentWaitBoundMs"`
	CoveredEvents             []string        `json:"coveredEvents"`
	Invariants                map[string]bool `json:"invariants"`
	JournalValidAfterEachStep bool            `json:"journalValidAfterEachStep"`
	CorruptionRejected        bool            `json:"corruptionRejected"`
	StopsWithLiveClient       int             `json:"stopsWithLiveClient"`
	DuplicateGenerationStops  int             `json:"duplicateGenerationStops"`
}

type modelCounters struct {
	mu                       sync.Mutex
	transitions              int
	scenarios                int
	covered                  map[string]bool
	invariants               map[string]bool
	stopsWithLiveClient      int
	duplicateGenerationStops int
}

// RunBoundedModelCheck executes deterministic finite sequences, persisted
// replay, and bounded concurrent replay against the production coordinator.
func RunBoundedModelCheck() (ModelCheckReport, error) {
	counters := &modelCounters{covered: map[string]bool{}, invariants: map[string]bool{}}
	sequences := modelConstrainedPermutations(
		[]string{"attach-a", "finish-a", "attach-b", "finish-b", "timeout", "boot-2"},
		func(sequence []string) bool {
			return modelIndexOf(sequence, "attach-a") < modelIndexOf(sequence, "finish-a") &&
				modelIndexOf(sequence, "attach-b") < modelIndexOf(sequence, "finish-b")
		},
	)
	if len(sequences) != modelExhaustiveSequenceCount {
		return ModelCheckReport{}, fmt.Errorf("lifecycle model sequence cardinality=%d want %d", len(sequences), modelExhaustiveSequenceCount)
	}
	for _, sequence := range sequences {
		if err := runModelSequence(sequence, counters); err != nil {
			return ModelCheckReport{}, err
		}
	}
	if err := runModelContractScenarios(counters); err != nil {
		return ModelCheckReport{}, err
	}
	if err := runModelPersistedReplays(counters); err != nil {
		return ModelCheckReport{}, err
	}
	if err := runModelConcurrentReplays(counters); err != nil {
		return ModelCheckReport{}, err
	}
	if err := verifyModelCoverage(counters); err != nil {
		return ModelCheckReport{}, err
	}
	report := ModelCheckReport{
		Schema: "hideout.lifecycle-model-evidence/v1", Status: "passed",
		ExhaustiveSequences: modelExhaustiveSequenceCount,
		ExploredTransitions: counters.transitions, ScenarioCount: counters.scenarios,
		PersistedReplaySeeds: modelPersistedReplaySeeds, ConcurrentReplaySeeds: modelConcurrentReplaySeeds,
		StepsPerPersistedReplay: modelReplaySteps, ConcurrentWaitBoundMS: int(modelConcurrentWaitBound / time.Millisecond),
		Invariants: counters.invariants, JournalValidAfterEachStep: counters.invariants["journalValidAfterEachStep"],
		CorruptionRejected: true, StopsWithLiveClient: counters.stopsWithLiveClient,
		DuplicateGenerationStops: counters.duplicateGenerationStops,
	}
	for event := range counters.covered {
		report.CoveredEvents = append(report.CoveredEvents, event)
	}
	sort.Strings(report.CoveredEvents)
	return report, nil
}

