type modelClock struct {
	mu     sync.Mutex
	now    time.Time
	timers []*modelTimer
}

type modelTimer struct {
	clock   *modelClock
	due     time.Time
	fn      func()
	stopped bool
	fired   bool
}

func (t *modelTimer) Stop() bool {
	t.clock.mu.Lock()
	defer t.clock.mu.Unlock()
	active := !t.stopped && !t.fired
	t.stopped = true
	return active
}

func (c *modelClock) after(delay time.Duration, fn func()) timerHandle {
	c.mu.Lock()
	defer c.mu.Unlock()
	timer := &modelTimer{clock: c, due: c.now.Add(delay), fn: fn}
	c.timers = append(c.timers, timer)
	return timer
}

func (c *modelClock) advance(delay time.Duration) {
	c.mu.Lock()
	c.now = c.now.Add(delay)
	var callbacks []func()
	for _, timer := range c.timers {
		if !timer.stopped && !timer.fired && !timer.due.After(c.now) {
			timer.fired = true
			callbacks = append(callbacks, timer.fn)
		}
	}
	c.mu.Unlock()
	for _, callback := range callbacks {
		callback()
	}
}

func (c *modelClock) current() time.Time {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.now
}

type modelStopBehavior struct {
	mu         sync.Mutex
	mode       string
	active     *int
	stopped    map[uint64]bool
	counters   *modelCounters
	clock      *modelClock
	instance   string
	invocation int
}

func (s *modelStopBehavior) stop(_ context.Context, request StopRequest) (StopResult, error) {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.invocation++
	if s.active != nil && *s.active != 0 {
		s.counters.stopsWithLiveClient++
		return StopResult{}, errors.New("model observed stop with live client")
	}
	if s.stopped[request.Incarnation.StartGeneration] {
		s.counters.duplicateGenerationStops++
		return StopResult{}, errors.New("model observed duplicate generation stop")
	}
	observedAt := s.clock.current()
	switch s.mode {
	case "failure":
		return StopResult{Observation: backend.LifecycleObservation{
			State: backend.LifecycleRunning, InstanceName: s.instance,
			BootID: request.Incarnation.BootID, ObservedAt: observedAt,
		}}, errors.New("injected backend stop failure")
	case "unknown":
		return StopResult{Observation: backend.LifecycleObservation{
			State: backend.LifecycleUnknown, InstanceName: s.instance,
			ObservedAt: observedAt, ReasonCode: "observation-unavailable",
		}}, nil
	default:
		s.stopped[request.Incarnation.StartGeneration] = true
		return StopResult{Observation: backend.LifecycleObservation{
			State: backend.LifecycleStopped, InstanceName: s.instance, ObservedAt: observedAt,
		}}, nil
	}
}

func newModelCoordinator(root, daemonID string, clock *modelClock, enabled bool, stop StopFunc) (*Coordinator, error) {
	return NewCoordinator(CoordinatorOptions{
		Store: JournalStore{Root: root}, DaemonID: daemonID, IdleGrace: DefaultIdleGrace,
		Now: clock.current, AfterFunc: clock.after, Stop: stop, Enabled: enabled,
	})
}

func modelObservation(clock *modelClock, bootID string, state backend.LifecycleState) backend.LifecycleObservation {
	observation := backend.LifecycleObservation{
		State: state, InstanceName: "hideout-model", ObservedAt: clock.current(),
	}
	if state == backend.LifecycleRunning {
		observation.BootID = bootID
	}
	if state == backend.LifecycleUnknown {
		observation.ReasonCode = "inventory-unavailable"
	}
	return observation
}

func modelAttach(coordinator *Coordinator, clock *modelClock, sessionID, bootID string) (Registration, error) {
	registration, err := coordinator.BeginAttach(context.Background(), AttachRequest{
		EnvironmentID: "env-model", InstanceName: "hideout-model", SessionID: sessionID,
		Observation: modelObservation(clock, bootID, backend.LifecycleRunning),
	})
	if err != nil {
		return nil, err
	}
	provider, err := registration.Register(context.Background(), RegistrationSpec{
		Kind: KindWorkspaceHostProvider, ID: "workspace-provider-shared",
		OwnerKind: "manager", OwnerID: "workspace-provider-shared", State: StatePlanned,
		Dependencies: []DependencySpec{{Ref: registration.Root(), StopMode: StopModeDrain}},
		Persistence:  PersistenceEphemeral, ClosePolicy: ClosePreStopDrain, PossibleVMDependency: true,
	})
	if err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	view, err := registration.Register(context.Background(), RegistrationSpec{
		Kind: KindWorkspaceGuestView, ID: "workspace-view-" + sessionID,
		OwnerKind: "session", OwnerID: sessionID, State: StatePlanned,
		Dependencies: []DependencySpec{
			{Ref: registration.Root(), StopMode: StopModeDrain},
			{Ref: registration.Session(), StopMode: StopModeDrain},
			{Ref: provider, StopMode: StopModeDrain},
		},
		Persistence: PersistenceEphemeral, ClosePolicy: ClosePreStopDrain, PossibleVMDependency: true,
	})
	if err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	if err := registration.Commit(context.Background()); err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	if err := registration.BindBoot(context.Background(), bootID); err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	if err := registration.Transition(context.Background(), provider, StateStarting); err != nil {
		if activeErr := registration.Transition(context.Background(), provider, StateActive); activeErr != nil {
			_ = registration.Finish(context.Background(), err)
			return nil, err
		}
	} else if err := registration.Transition(context.Background(), provider, StateActive); err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	for _, state := range []ResourceState{StateStarting, StateActive} {
		if err := registration.Transition(context.Background(), view, state); err != nil {
			_ = registration.Finish(context.Background(), err)
			return nil, err
		}
	}
	if err := registration.Transition(context.Background(), registration.Session(), StateActive); err != nil {
		_ = registration.Finish(context.Background(), err)
		return nil, err
	}
	return registration, nil
}

func runModelSequence(sequence []string, counters *modelCounters) error {
	root, err := os.MkdirTemp("", "hideout-lifecycle-model-sequence-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(root)
	if err := os.Chmod(root, 0o700); err != nil {
		return err
	}
	clock := &modelClock{now: time.Date(2026, 7, 16, 5, 0, 0, 0, time.UTC)}
	active := 0
	stopper := &modelStopBehavior{active: &active, stopped: map[uint64]bool{}, counters: counters, clock: clock, instance: "hideout-model"}
	coordinator, err := newModelCoordinator(root, "daemon-model-sequence", clock, true, stopper.stop)
	if err != nil {
		return err
	}
	registrations := map[string]Registration{}
	bootOne := "01234567-89ab-cdef-0123-456789abcdef"
	bootTwo := "aaaaaaaa-bbbb-cccc-dddd-eeeeeeeeeeee"
	for step, event := range sequence {
		switch event {
		case "attach-a", "attach-b":
			client := strings.TrimPrefix(event, "attach-")
			registration, attachErr := modelAttach(coordinator, clock, "ses-"+client, bootOne)
			if attachErr == nil {
				registrations[client] = registration
				active++
				counters.cover("attach", "activate", "workspace-provider-activate", "workspace-view-activate")
			}
		case "finish-a", "finish-b":
			client := strings.TrimPrefix(event, "finish-")
			if registration := registrations[client]; registration != nil {
				if finishErr := registration.Finish(context.Background(), nil); finishErr == nil {
					active--
					counters.cover("release", "workspace-view-release")
					if active != 0 {
						statuses := coordinator.Snapshot()
						if len(statuses) != 1 || statuses[0].Activity != ActivityPinned {
							return fmt.Errorf("sequence %v step %d sibling release lost the other owner: %+v", sequence, step, statuses)
						}
						if !modelStatusHasResource(statuses[0], KindWorkspaceHostProvider, StateActive) {
							return fmt.Errorf("sequence %v step %d sibling release removed shared workspace provider: %+v", sequence, step, statuses)
						}
						counters.passInvariant("siblingReleasePreservesOtherOwner", "workspaceSiblingProviderPreserved")
					} else {
						counters.cover("workspace-provider-last-release")
					}
				}
				delete(registrations, client)
			}
		case "timeout":
			clock.advance(DefaultIdleGrace)
			counters.cover("timeout", "stop-request", "stop-command-success", "backend-observation-success")
		case "boot-2":
			if started, beginErr := coordinator.BeginReconciliation(context.Background(), "env-model"); beginErr == nil && started {
				reconcileErr := coordinator.Reconcile(context.Background(), ReconcileInput{
					EnvironmentID: "env-model", InstanceName: "hideout-model",
					Observation: modelObservation(clock, bootTwo, backend.LifecycleRunning),
				})
				if active != 0 && reconcileErr == nil {
					return fmt.Errorf("sequence %v step %d replaced incarnation with %d active clients", sequence, step, active)
				}
				if reconcileErr == nil {
					counters.cover("external-boot-change", "recovery")
				}
			}
		}
		counters.step()
		if err := validateModelCoordinator(coordinator, counters); err != nil {
			return fmt.Errorf("sequence %v step %d event %s: %w", sequence, step, event, err)
		}
	}
	if err := coordinator.Close(); err != nil {
		return fmt.Errorf("sequence %v close: %w", sequence, err)
	}
	counters.scenario()
	return nil
}

func runModelContractScenarios(counters *modelCounters) error {
	if err := runModelResourceAndSuccessfulStop(counters); err != nil {
		return err
	}
	for _, mode := range []string{"failure", "unknown"} {
		if err := runModelUnprovedStop(mode, counters); err != nil {
			return err
		}
	}
	if err := runModelCrashAndRecovery(counters); err != nil {
		return err
	}
	if err := runModelClientCrash(counters); err != nil {
		return err
	}
	return nil
}

func runModelResourceAndSuccessfulStop(counters *modelCounters) error {
	root, err := os.MkdirTemp("", "hideout-lifecycle-model-resource-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(root)
	_ = os.Chmod(root, 0o700)
	clock := &modelClock{now: time.Date(2026, 7, 16, 6, 0, 0, 0, time.UTC)}
	active := 1
	stopper := &modelStopBehavior{active: &active, stopped: map[uint64]bool{}, counters: counters, clock: clock, instance: "hideout-model"}
	coordinator, err := newModelCoordinator(root, "daemon-model-resource", clock, true, stopper.stop)
	if err != nil {
		return err
	}
	registration, err := modelAttach(coordinator, clock, "ses-resource", "01234567-89ab-cdef-0123-456789abcdef")
	if err != nil {
		return err
	}
	bridge, err := registration.Register(context.Background(), RegistrationSpec{
		Kind: KindRunBridge, ID: "bridge-resource", OwnerKind: "session", State: StatePlanned,
		Dependencies: []DependencySpec{{Ref: registration.Root(), StopMode: StopModePin}, {Ref: registration.Session(), StopMode: StopModeDrain}},
		Persistence:  PersistenceEphemeral, ClosePolicy: ClosePreStopDrain, PossibleVMDependency: true,
	})
	if err != nil {
		return err
	}
	for _, state := range []ResourceState{StateStarting, StateActive} {
		if err := registration.Transition(context.Background(), bridge, state); err != nil {
			return err
		}
	}
	if err := registration.RecordFact(context.Background(), FactSpec{Kind: KindHostFSStaged, ID: "staged-resource", Class: FactRetained}); err != nil {
		return err
	}
	if err := registration.RecordFact(context.Background(), FactSpec{Kind: KindHostAppHandoff, ID: "handoff-resource", Class: FactHandoff}); err != nil {
		return err
	}
	counters.cover("attach", "activate", "vm-bound-bridge", "retained-overlay", "host-only-handoff", "workspace-provider-activate", "workspace-view-activate")
	if err := validateModelCoordinator(coordinator, counters); err != nil {
		return err
	}
	if err := registration.Release(context.Background(), bridge, nil); err != nil {
		return err
	}
	active = 0
	if err := registration.Finish(context.Background(), nil); err != nil {
		return err
	}
	counters.cover("release", "workspace-view-release", "workspace-provider-last-release")
	clock.advance(DefaultIdleGrace)
	counters.cover("timeout", "stop-request", "stop-command-success", "backend-observation-success")
	statuses := coordinator.Snapshot()
	if len(statuses) != 1 || statuses[0].Activity != ActivityStopped || len(statuses[0].Retained) != 1 || len(statuses[0].Handoffs) != 1 {
		return fmt.Errorf("successful stop did not preserve independent facts: %+v", statuses)
	}
	counters.passInvariant("retainedStateDoesNotPin", "stoppedRootHasNoLiveDependent", "workspaceResourcesAbsentBeforeStop")
	if err := validateModelCoordinator(coordinator, counters); err != nil {
		return err
	}
	if err := coordinator.Close(); err != nil {
		return err
	}
	counters.scenario()
	return nil
}

